# -*- coding: utf-8 -*-
"""按关系给起草模型的「说话分寸」参考。

**这不是话术库。** 网上那种「高情商回复语录」是这个项目最该躲开的东西——
它们本身就很人机：油腻（「能被你珍惜，我才愿意温柔以待」）、全是同一个套路
（接住夸奖再反夸回去）、而且是拍给「让说话的人显得会说话」用的，不是让对话进行下去的。

这里给的是**分寸**：这段关系里，说多长算正常、能不能损人、要不要留余地。
另外每种关系配一段极短的示范对话——**示范的是节奏，不是让你照抄那些句子**。

起草时按 relationship 自动带上（core/draft.py）。用户填的是自定义关系就没有这一段，
那也合理：不清楚分寸的时候，宁可让它照着口吻样本模仿。
"""
from __future__ import annotations

# 键是界面「你们的关系」那几项对应的英文值，见 app/overlay.py 的 _RELATIONSHIPS。
# 用户选「自定义」时 relationship 是自由文本，查不到就返回空串。
_REGISTERS = {
    "romantic partners": """这段关系里怎么说话：
- 只说半句很正常，剩下让对方追问；说太完整反而见外。
- 撒娇、耍赖、示弱都算正常表达，不算失态。
- 别用「我理解你的感受」这种咨询师口吻——那是跟陌生人说话的方式。
- 想说什么直接说，「我想你」不用包装成别的。
- 认错就认错，别在认错后面接「但是」。
节奏示范（看长短和停顿，别抄句子）：
  对方：今天好累
  我：几点回 我去接你
  对方：你是不是又忘了
  我：……忘了
  我：等我翻一下""",

    "friends": """这段关系里怎么说话：
- 可以损、可以敷衍、可以只回两三个字；一本正经反而奇怪。
- 别用完整句子，别加敬语——「感谢分享」这种客气话最伤朋友感情。
- 不用每次都接住话题，回个「行」「草」也算回了。
- 对方吐槽的时候，跟着骂比给建议管用。
节奏示范（看长短和停顿，别抄句子）：
  对方：周六有空吗
  我：干嘛
  我：有空
  对方：我昨天喝多了
  我：活该""",

    "colleagues": """这段关系里怎么说话：
- 不说满，留余地：「我看看」「尽量」「有消息回你」比「没问题」安全。
- 别替对方做决定，也别替别的同事表态。
- 答应之前先给时间点，光说「好的」等于没说。
- 称呼稳，不用昵称、不玩梗。
- 别秒回一大段，显得刻意。
节奏示范（看长短和停顿，别抄句子）：
  对方：这个今天能给我吗
  我：我下午看一下，快的话今天，不然明早
  对方：辛苦了
  我：没事""",

    "family": """这段关系里怎么说话：
- 先应声，别先讲道理。「知道了」「我记住了」比一段解释管用得多。
- 长辈说的事，除非要紧，不用纠正事实。
- 家里的事不谈判，直接答应或者直接说做不到。
- 别用「您放心」这种客套，家人之间客气反而生分。
节奏示范（看长短和停顿，别抄句子）：
  对方：天冷了多穿点
  我：知道啦
  对方：什么时候回来
  我：下周末 我提前跟你说""",
}


# 界面下拉那几个中文标签也认。用户选「自定义」时 relationship 是他手打的自由文本，
# 打「朋友」的概率不低；命令行脚本（tools/demo.py）里写的也是中文标签。
# 只认界面上那几个标准词，不做模糊匹配——猜错了会给错的分寸，还不如不给。
_ALIASES = {
    "恋人": "romantic partners", "情侣": "romantic partners",
    "朋友": "friends",
    "同事": "colleagues",
    "家人": "family",
}


def register_for(relationship: str) -> str:
    """这段关系的说话分寸；没有对应的一段就返回空串（自定义关系、或者值对不上）。"""
    key = (relationship or "").strip()
    return _REGISTERS.get(_ALIASES.get(key, key.lower()), "")


if __name__ == "__main__":
    # ponytail: 纯数据，只查几条不变式——键得跟界面那几个关系值对得上，
    # 少一个就是「选了朋友却没有分寸参考」，静默失效。
    assert set(_REGISTERS) == {"romantic partners", "friends", "colleagues", "family"}, set(_REGISTERS)
    assert all(v.strip() for v in _REGISTERS.values())
    assert register_for("friends") and register_for("FRIENDS")  # 大小写不该影响
    # 界面那几个中文标签也认——选「自定义」手打「朋友」、或者命令行脚本里写的都是中文
    assert register_for("朋友") == _REGISTERS["friends"]
    assert register_for(" 同事 ") == _REGISTERS["colleagues"]   # 前后空格要洗掉
    assert register_for("") == "" and register_for(None) == ""
    assert register_for("刚认识的朋友") == ""   # 不做模糊匹配：猜错了给错分寸，不如不给
    # 每段都得带一段示范，光有策略模型学不到节奏
    assert all("示范" in v for v in _REGISTERS.values())
    print(f"register ok · {len(_REGISTERS)} 种关系")
